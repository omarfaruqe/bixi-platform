"""Train, backtest and save the forecasting models (Step 6).

Usage, from the project root (after: pip install -e ".[ml]"):
    python -m bixi.models            # full run: backtests, holdout, final models, report
    python -m bixi.models --quick    # one fold and the main model only (smoke test)

Outputs:
    data/processed/model_results/*.parquet   predictions and metric tables (read by the dashboard)
    data/models/<target>_{mean,q10,q90}.txt  final models for serving (Step 7), with .json metadata
    docs/model_results.md                    the results summary (generated; commit it)
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from datetime import UTC, datetime, timedelta
from pathlib import Path

import polars as pl

from bixi.config import get_settings
from bixi.features.build import TARGETS
from bixi.models import lgbm
from bixi.models.backtest import FOLDS, VALID_DAYS, metric_tables, run, variants
from bixi.models.metrics import conformal_margin, skill
from bixi.models.names import INTERVAL, MAIN

REPORT = Path("docs/model_results.md")


def _fmt(value: float, digits: int = 3) -> str:
    return "n/a" if value is None else f"{value:.{digits}f}"


HEADER = "| Model | MAE | RMSE | Poisson deviance | Skill vs naive | 80% coverage | Purpose |"


def _row(r: dict, naive_mae: float | None, purposes: dict[str, str]) -> str:
    gain = f"{skill(r['mae'], naive_mae):.1%}" if naive_mae else "n/a"
    cov = r.get("coverage")
    coverage = f"{cov:.1%}" if cov is not None else ""
    if r["model"] in purposes:
        purpose = purposes[r["model"]]
    elif r["model"] == "poisson_assumption_interval":
        purpose = "interval reference: Poisson assumption"
    elif r["model"] == "quantile_raw_interval":
        purpose = "interval reference: quantiles before conformal calibration"
    else:
        purpose = "baseline"
    return (
        f"| {r['model']} | {_fmt(r['mae'])} | {_fmt(r['rmse'])} | {_fmt(r['poisson_deviance'])} "
        f"| {gain} | {coverage} | {purpose} |"
    )


def write_report(tables: dict[str, pl.DataFrame], importance: pl.DataFrame, path: Path) -> str:
    overall = tables["metrics_overall"]
    purposes = {v.name: v.purpose for v in variants()}
    lines = [
        "# Model results (generated by `python -m bixi.models`)",
        "",
        "Hourly departures and arrivals at the 50 study stations, forecast up to 24 hours ahead.",
        "Backtest: four monthly folds (June-September 2025). Holdout: 2025-10-01 to 2025-11-15,",
        "evaluated once. Skill = MAE reduction versus the seasonal naive baseline",
        "(same hour last week).",
        "",
    ]
    for split_name in ("backtest", "holdout"):
        lines += [f"## {split_name.capitalize()}", ""]
        for target in TARGETS:
            rows = overall.filter((pl.col("split") == split_name) & (pl.col("target") == target))
            naive = rows.filter(pl.col("model") == "seasonal_naive")["mae"]
            naive_mae = naive[0] if naive.len() else None
            lines += [
                f"### {target.capitalize()}",
                "",
                HEADER,
                "|---|---|---|---|---|---|---|",
            ]
            for r in rows.sort("mae").iter_rows(named=True):
                lines.append(_row(r, naive_mae, purposes))
            lines.append("")
    if not importance.is_empty():
        lines += ["## Top features (main model, holdout, share of gain)", ""]
        for target in TARGETS:
            top = importance.filter(pl.col("target") == target).head(10)
            lines.append(
                f"- **{target}**: "
                + ", ".join(
                    f"{f} {g:.0%}" for f, g in top.select("feature", "gain_share").iter_rows()
                )
            )
        lines.append("")
    text = "\n".join(lines)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return text


def train_final(df: pl.DataFrame, out_dir: Path, max_rounds: int) -> dict:
    """Production models on 2024-2025, early-stopping on the last 14 days of 2025."""
    last = df["local_date"].max()
    valid_start = last - timedelta(days=VALID_DAYS - 1)
    window = df.filter(pl.col("year") >= 2024)
    train = window.filter(pl.col("local_date") < valid_start)
    valid = window.filter(pl.col("local_date") >= valid_start)
    main = next(v for v in variants() if v.name == MAIN)
    encoding = lgbm.Encoding.fit(df)
    summary = {}
    margins = {}
    for target in TARGETS:
        fitted = {}
        for suffix, objective, alpha in (
            ("mean", main.objective, None),
            ("q10", "quantile", INTERVAL[0]),
            ("q90", "quantile", INTERVAL[1]),
        ):
            model = lgbm.fit(
                train, valid, target, main.features, objective, alpha, encoding, max_rounds
            )
            model.save(out_dir / f"{target}_{suffix}.txt")
            summary[f"{target}_{suffix}"] = model.best_iteration
            fitted[suffix] = model
        # Serving widens [q10, q90] by this margin (split conformal, last 14 days of 2025).
        margins[target] = conformal_margin(
            valid[target].cast(pl.Float64).to_numpy(),
            fitted["q10"].predict(valid),
            fitted["q90"].predict(valid),
            INTERVAL[1] - INTERVAL[0],
        )
    manifest = {
        "trained_at_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "trained_through_local_date": str(last),
        "variant": MAIN,
        "interval": list(INTERVAL),
        "rounds": summary,
        "interval_conformal_margin": margins,
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return manifest


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Backtest and train the BIXI forecasting models")
    parser.add_argument("--quick", action="store_true", help="one fold, main model only")
    args = parser.parse_args(argv)

    settings = get_settings()
    features_path = settings.processed_dir / "features.parquet"
    if not features_path.exists():
        print(f"Missing {features_path}. Run: python -m bixi.features")
        return 1
    df = pl.read_parquet(features_path)

    t0 = time.perf_counter()
    folds = FOLDS[-1:] if args.quick else FOLDS
    variant_list = [v for v in variants() if v.name == MAIN] if args.quick else None
    max_rounds = 300 if args.quick else lgbm.MAX_ROUNDS
    pred, importance, _ = run(df, folds, variant_list, max_rounds=max_rounds)

    out = settings.processed_dir / "model_results"
    out.mkdir(parents=True, exist_ok=True)
    pred.write_parquet(out / "predictions.parquet")
    importance.write_parquet(out / "importance.parquet")
    tables = metric_tables(pred)
    for name, table in tables.items():
        table.write_parquet(out / f"{name}.parquet")

    manifest = train_final(df, settings.data_dir / "models", max_rounds)
    text = write_report(tables, importance, REPORT)
    print(text)
    print(f"\nFinal models: {manifest['rounds']}")
    print(f"Done in {time.perf_counter() - t0:,.0f} s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
