"""Summaries of rebalancing results for the report and the dashboard.

Free of Streamlit and OR-Tools, so the dashboard image can import it.
"""

from __future__ import annotations

from pathlib import Path

import polars as pl

STRATEGY_ORDER = ("none", "rule_forecast", "optimized_forecast", "optimized_oracle")


def summarize(results: pl.DataFrame) -> pl.DataFrame:
    """Per scenario and strategy: daily means, and the reduction in problem hours versus none."""
    keys = ["start_fill", "trucks"]
    daily = results.group_by(*keys, "strategy").agg(
        pl.len().alias("days"),
        pl.col("empty_hours").mean(),
        pl.col("full_hours").mean(),
        pl.col("problem_hours").mean(),
        pl.col("missing_bikes").mean(),
        pl.col("missing_docks").mean(),
        pl.col("bikes_moved").mean(),
        pl.col("truck_km").mean(),
        pl.col("unmet_target_bikes").mean(),
    )
    none = daily.filter(pl.col("strategy") == "none").select(
        *keys, pl.col("problem_hours").alias("_none")
    )
    oracle = daily.filter(pl.col("strategy") == "optimized_oracle").select(
        *keys, pl.col("problem_hours").alias("_oracle")
    )
    order = {s: i for i, s in enumerate(STRATEGY_ORDER)}
    return (
        daily.join(none, on=keys)
        .join(oracle, on=keys, how="left")
        .with_columns(
            reduction=1 - pl.col("problem_hours") / pl.col("_none"),
            # Share of the improvement perfect foresight would achieve.
            share_of_oracle=pl.when(pl.col("_none") > pl.col("_oracle"))
            .then(
                (pl.col("_none") - pl.col("problem_hours")) / (pl.col("_none") - pl.col("_oracle"))
            )
            .otherwise(None),
            _o=pl.col("strategy").replace_strict(order, return_dtype=pl.Int8),
        )
        .sort(*keys, "_o")
        .drop("_none", "_oracle", "_o")
    )


def scenario(summary: pl.DataFrame, start_fill: float, trucks: int) -> pl.DataFrame:
    return summary.filter((pl.col("start_fill") == start_fill) & (pl.col("trucks") == trucks))


def write_report(
    summary: pl.DataFrame, results: pl.DataFrame, default, days: int, path: Path
) -> str:
    lines = [
        "# Rebalancing results (generated by `python -m bixi.rebalancing`)",
        "",
        f"{days} days (the Step 7 forecast run). Plans use day-ahead forecasts; every day is",
        "scored with the flows that actually happened. A problem hour is a station-hour in which",
        "some departures found no bike (empty) or some arrivals found no free dock (full).",
        "",
        f"Assumptions: trucks carry {default.truck_capacity} bikes, "
        f"drive at {default.speed_kmh:g} km/h",
        f"(x{default.detour_factor:g} detour), {default.stop_minutes:g} min per stop, "
        f"{default.minutes_per_bike:g} min per bike; rebalancing windows "
        + ", ".join(f"{s}-{e} h" for s, e in default.windows)
        + "; dock counts from the live feed, no staffed overflow docking.",
        "",
        f"## Default scenario: stations {default.start_fill:.0%} full at midnight, "
        f"{default.trucks} trucks",
        "",
        "| Strategy | Problem hours / day | Empty | Full | Reduction | Share of perfect foresight "
        "| Bikes moved / day | Truck km / day |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in scenario(summary, default.start_fill, default.trucks).iter_rows(named=True):
        share = "" if r["share_of_oracle"] is None else f"{r['share_of_oracle']:.0%}"
        lines.append(
            f"| {r['strategy']} | {r['problem_hours']:.0f} | {r['empty_hours']:.0f} | "
            f"{r['full_hours']:.0f} | {r['reduction']:.1%} | {share} | {r['bikes_moved']:.0f} | "
            f"{r['truck_km']:.0f} |"
        )
    lines += [
        "",
        "## Sensitivity: reduction in problem hours, optimized plan from forecasts",
        "",
        "| Starting fill | 1 truck | 2 trucks | 4 trucks |",
        "|---|---|---|---|",
    ]
    opt = summary.filter(pl.col("strategy") == "optimized_forecast")
    for fill in sorted(opt["start_fill"].unique().to_list()):
        cells = []
        for trucks in (1, 2, 4):
            row = opt.filter((pl.col("start_fill") == fill) & (pl.col("trucks") == trucks))
            cells.append(f"{row['reduction'][0]:.1%}" if row.height else "")
        lines.append(f"| {fill:.0%} | " + " | ".join(cells) + " |")
    text = "\n".join(lines) + "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return text
